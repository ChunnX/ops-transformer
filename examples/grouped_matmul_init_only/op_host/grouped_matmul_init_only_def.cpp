/*!
 * \file grouped_matmul_init_only_def.cpp
 * \brief
 */
#include "register/op_def_registry.h"

namespace ops {
class GroupedMatmulInitOnly : public OpDef
{
public:
    explicit GroupedMatmulInitOnly(const char* name) : OpDef(name)
    {
        this->Input("x")                                        // 输入 x: [M, K] fp16
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16})
            .Format({ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND})
            .AutoContiguous();
        this->Input("weight")                                   // 输入 weight: [G, K, N] fp16
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16})
            .Format({ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND})
            .AutoContiguous();
        this->Input("group_list")                               // 输入 group_list: [G] int64
            .ParamType(REQUIRED)
            .DataType({ge::DT_INT64})
            .Format({ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND})
            .AutoContiguous();
        this->Output("y")                                       // 输出 y: [M, N] fp16
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16})
            .Format({ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND})
            .AutoContiguous();

        OpAICoreConfig aicoreConfig;
        aicoreConfig.DynamicCompileStaticFlag(true)
            .DynamicFormatFlag(false)
            .DynamicRankSupportFlag(true)
            .DynamicShapeSupportFlag(true)
            .NeedCheckSupportFlag(false)
            .PrecisionReduceFlag(true)
            .ExtendCfgInfo("opFile.value", "grouped_matmul_init_only"); // 对应到 kernel 入口文件名 .cpp
        this->AICore().AddConfig("ascend910b", aicoreConfig);
        this->AICore().AddConfig("ascend910_93", aicoreConfig);
        this->AICore().AddConfig("ascend950", aicoreConfig);
    }
};
OP_ADD(GroupedMatmulInitOnly); // 添加算子信息库
} // namespace ops
