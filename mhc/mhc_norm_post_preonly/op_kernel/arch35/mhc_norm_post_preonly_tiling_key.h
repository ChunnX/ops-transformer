#ifndef MHC_NORM_POST_PREONLY_TILING_KEY_H_
#define MHC_NORM_POST_PREONLY_TILING_KEY_H_

#include "ascendc/host_api/tiling/template_argument.h"

// 低三位编码：[dualSibling, returnHInF32, useRmsMid]；第4位表示大D的UB partial累积。
// 0~7 为原路径，8~15 为 D=6144/7168 的编译期特化路径。
#define TILING_KEY_SINGLE_4OP 0
#define TILING_KEY_SINGLE_5OP 1
#define TILING_KEY_SINGLE_4OP_RETURN_F32 2
#define TILING_KEY_SINGLE_5OP_RETURN_F32 3
#define TILING_KEY_DUAL_4OP 4
#define TILING_KEY_DUAL_5OP 5
#define TILING_KEY_DUAL_4OP_RETURN_F32 6
#define TILING_KEY_DUAL_5OP_RETURN_F32 7
#define TILING_KEY_LARGE_D_OFFSET 8

ASCENDC_TPL_ARGS_DECL(
    MhcNormPostPreonly,
    ASCENDC_TPL_UINT_DECL(TILING_MODE, ASCENDC_TPL_4_BW, ASCENDC_TPL_UI_LIST, TILING_KEY_SINGLE_4OP,
                          TILING_KEY_SINGLE_5OP, TILING_KEY_SINGLE_4OP_RETURN_F32,
                          TILING_KEY_SINGLE_5OP_RETURN_F32, TILING_KEY_DUAL_4OP, TILING_KEY_DUAL_5OP,
                          TILING_KEY_DUAL_4OP_RETURN_F32, TILING_KEY_DUAL_5OP_RETURN_F32,
                          8, 9, 10, 11, 12, 13, 14, 15));

ASCENDC_TPL_SEL(
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_AIV_ONLY),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, TILING_KEY_SINGLE_4OP)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_AIV_ONLY),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, TILING_KEY_SINGLE_5OP)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_AIV_ONLY),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, TILING_KEY_SINGLE_4OP_RETURN_F32)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_AIV_ONLY),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, TILING_KEY_SINGLE_5OP_RETURN_F32)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_MIX_AIC_1_2),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, TILING_KEY_DUAL_4OP)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_MIX_AIC_1_2),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, TILING_KEY_DUAL_5OP)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_MIX_AIC_1_2),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, TILING_KEY_DUAL_4OP_RETURN_F32)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_MIX_AIC_1_2),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, TILING_KEY_DUAL_5OP_RETURN_F32)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_AIV_ONLY),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, 8)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_AIV_ONLY),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, 9)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_AIV_ONLY),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, 10)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_AIV_ONLY),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, 11)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_MIX_AIC_1_2),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, 12)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_MIX_AIC_1_2),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, 13)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_MIX_AIC_1_2),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, 14)),
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_KERNEL_TYPE_SEL(ASCENDC_TPL_MIX_AIC_1_2),
                         ASCENDC_TPL_UINT_SEL(TILING_MODE, ASCENDC_TPL_UI_LIST, 15)));

#endif // MHC_NORM_POST_PREONLY_TILING_KEY_H_
