namespace {

constexpr int64_t MAX_LEVELS = 5;

struct CaseMeta {
    std::string name;
    int64_t levels = 1;
    int64_t batch = 1;
    int64_t channels = 1;
    int64_t levelH[MAX_LEVELS] = {1, 1, 1, 1, 1};
    int64_t levelW[MAX_LEVELS] = {1, 1, 1, 1, 1};
    int64_t roisNum = 0;
    aclDataType dtype = ACL_FLOAT;
    int64_t pooledH = 7;
    int64_t pooledW = 7;
    int64_t sampleNum = 0;
    int64_t finestScale = 56;
    double roiScaleFactor = 0.0;
    float spatialScale[MAX_LEVELS] = {0.25f, 0.125f, 0.0625f, 0.03125f, 0.015625f};
    int64_t spatialScaleLen = 0;
    std::string poolMode = "avg";
    bool aligned = true;
};

std::string Trim(const std::string &s)
{
    size_t b = s.find_first_not_of(" \t\r\n");
    if (b == std::string::npos) {
        return "";
    }
    size_t e = s.find_last_not_of(" \t\r\n");
    return s.substr(b, e - b + 1);
}

// minimal key=value parser for the JSON generated by golden.py (flat object)
std::string JsonValue(const std::string &text, const std::string &key)
{
    std::string pat = "\"" + key + "\"";
    size_t p = text.find(pat);
    if (p == std::string::npos) {
        return "";
    }
    p = text.find(':', p + pat.size());
    if (p == std::string::npos) {
        return "";
    }
    size_t v = text.find_first_not_of(" \t", p + 1);
    if (v == std::string::npos) {
        return "";
    }
    if (text[v] == '"') {
        size_t e = text.find('"', v + 1);
        return text.substr(v + 1, e - v - 1);
    }
    size_t e = text.find_first_of(",}\n\r", v);
    return Trim(text.substr(v, e - v));
}

int64_t AsInt(const std::string &s)
{
    return std::stoll(s);
}

bool LoadCase(const std::string &dir, CaseMeta &meta, std::vector<std::vector<char>> &featsData,
              std::vector<char> &roisData, std::vector<float> &golden)
{
    std::ifstream mf(dir + "/meta.json");
    if (!mf.is_open()) {
        printf("open meta.json failed: %s\n", dir.c_str());
        return false;
    }
    std::stringstream ss;
    ss << mf.rdbuf();
    const std::string text = ss.str();

    meta.name = JsonValue(text, "name");
    meta.levels = AsInt(JsonValue(text, "levels"));
    meta.batch = AsInt(JsonValue(text, "batch"));
    meta.channels = AsInt(JsonValue(text, "channels"));
    meta.roisNum = AsInt(JsonValue(text, "rois_num"));
    meta.pooledH = AsInt(JsonValue(text, "pooled_h"));
    meta.pooledW = AsInt(JsonValue(text, "pooled_w"));
    meta.sampleNum = AsInt(JsonValue(text, "sample_num"));
    meta.finestScale = AsInt(JsonValue(text, "finest_scale"));
    meta.roiScaleFactor = std::stod(JsonValue(text, "roi_scale_factor"));
    meta.poolMode = JsonValue(text, "pool_mode");
    meta.aligned = (JsonValue(text, "aligned") == "true");
    const std::string dtype = JsonValue(text, "dtype");
    meta.dtype = (dtype == "float16") ? ACL_FLOAT16 : ACL_FLOAT;

    // level_hw: [[h, w], ...] and spatial_scale: [s0, s1, ...]
    {
        size_t p = text.find("\"level_hw\"");
        size_t start = text.find('[', p);
        int lvl = 0;
        size_t cur = start + 1;
        while (lvl < meta.levels) {
            size_t open = text.find('[', cur);
            size_t close = text.find(']', open);
            std::string pair = text.substr(open + 1, close - open - 1);
            size_t comma = pair.find(',');
            meta.levelH[lvl] = AsInt(Trim(pair.substr(0, comma)));
            meta.levelW[lvl] = AsInt(Trim(pair.substr(comma + 1)));
            lvl++;
            cur = close + 1;
        }
        size_t ps = text.find("\"spatial_scale\"");
        size_t starts = text.find('[', ps);
        size_t ends = text.find(']', starts);
        std::string slist = text.substr(starts + 1, ends - starts - 1);
        std::stringstream sl(slist);
        std::string item;
        int idx = 0;
        while (std::getline(sl, item, ',') && idx < MAX_LEVELS) {
            meta.spatialScale[idx] = std::stof(Trim(item));
            idx++;
        }
        meta.spatialScaleLen = idx;
    }

    const size_t elemSize = (meta.dtype == ACL_FLOAT16) ? 2 : 4;
    featsData.clear();
    for (int64_t l = 0; l < meta.levels; l++) {
        std::ifstream f(dir + "/feats_l" + std::to_string(l) + ".bin", std::ios::binary);
        if (!f.is_open()) {
            printf("open feats_l%d failed\n", (int)l);
            return false;
        }
        const size_t bytes = static_cast<size_t>(meta.batch * meta.channels * meta.levelH[l] * meta.levelW[l]) * elemSize;
        std::vector<char> buf(bytes);
        f.read(buf.data(), static_cast<std::streamsize>(bytes));
        featsData.push_back(std::move(buf));
    }
    {
        std::ifstream f(dir + "/rois.bin", std::ios::binary);
        const size_t bytes = static_cast<size_t>(meta.roisNum) * 5 * elemSize;
        roisData.resize(bytes);
        f.read(roisData.data(), static_cast<std::streamsize>(bytes));
    }
    {
        std::ifstream f(dir + "/golden.bin", std::ios::binary);
        const size_t elems = static_cast<size_t>(meta.roisNum * meta.channels * meta.pooledH * meta.pooledW);
        golden.resize(elems);
        f.read(reinterpret_cast<char *>(golden.data()), static_cast<std::streamsize>(elems * 4));
    }
    return true;
}

bool RunOneCase(int32_t deviceId, const std::string &dir, std::string &caseName, bool &pass)
{
    CaseMeta meta;
    std::vector<std::vector<char>> featsData;
    std::vector<char> roisData;
    std::vector<float> golden;
    if (!LoadCase(dir, meta, featsData, roisData, golden)) {
        return false;
    }
    caseName = meta.name;


    if (aclrtSetDevice(deviceId) != ACL_SUCCESS) {
        printf("set device %d failed\n", deviceId);
        return false;
    }
    aclrtStream stream = nullptr;
    aclrtCreateStream(&stream);

    // upload feats / rois
    std::vector<void *> featsDev(static_cast<size_t>(meta.levels), nullptr);
    for (int64_t l = 0; l < meta.levels; l++) {
        const size_t bytes = featsData[static_cast<size_t>(l)].size();
        aclrtMalloc(&featsDev[static_cast<size_t>(l)], bytes, ACL_MEM_MALLOC_HUGE_FIRST);
        aclrtMemcpy(featsDev[static_cast<size_t>(l)], bytes, featsData[static_cast<size_t>(l)].data(), bytes,
                    ACL_MEMCPY_HOST_TO_DEVICE);
    }
    const size_t roisBytes = roisData.size();
    void *roisDev = nullptr;
    aclrtMalloc(&roisDev, roisBytes, ACL_MEM_MALLOC_HUGE_FIRST);
    aclrtMemcpy(roisDev, roisBytes, roisData.data(), roisBytes, ACL_MEMCPY_HOST_TO_DEVICE);

    // device tensors
    std::vector<aclTensor *> featsT(static_cast<size_t>(meta.levels), nullptr);
    for (int64_t l = 0; l < meta.levels; l++) {
        std::vector<int64_t> dims = {meta.batch, meta.channels, meta.levelH[l], meta.levelW[l]};
        std::vector<int64_t> strides = {meta.channels * meta.levelH[l] * meta.levelW[l],
                                        meta.levelH[l] * meta.levelW[l], meta.levelW[l], 1};
        featsT[static_cast<size_t>(l)] = aclCreateTensor(dims.data(), dims.size(), meta.dtype, strides.data(), 0,
                                                         ACL_FORMAT_ND, dims.data(), dims.size(),
                                                         featsDev[static_cast<size_t>(l)]);
    }
    const aclTensorList *featsList = aclCreateTensorList(const_cast<const aclTensor **>(featsT.data()),
                                                         static_cast<uint64_t>(meta.levels));
    std::vector<int64_t> roisDims = {meta.roisNum, 5};
    std::vector<int64_t> roisStrides = {5, 1};
    auto roisT = aclCreateTensor(roisDims.data(), roisDims.size(), meta.dtype, roisStrides.data(), 0, ACL_FORMAT_ND,
                                 roisDims.data(), roisDims.size(), roisDev);
    std::vector<int64_t> yDims = {meta.roisNum, meta.channels, meta.pooledH, meta.pooledW};
    std::vector<int64_t> yStrides = {meta.channels * meta.pooledH * meta.pooledW, meta.pooledH * meta.pooledW,
                                     meta.pooledW, 1};
    const size_t yBytes = golden.size() * 4;
    void *yDev = nullptr;
    aclrtMalloc(&yDev, yBytes, ACL_MEM_MALLOC_HUGE_FIRST);
    auto yT = aclCreateTensor(yDims.data(), yDims.size(), meta.dtype, yStrides.data(), 0, ACL_FORMAT_ND,
                              yDims.data(), yDims.size(), yDev);

    auto scaleArr = aclCreateFloatArray(meta.spatialScale, static_cast<uint64_t>(meta.spatialScaleLen));
    char poolMode[8] = {0};
    snprintf(poolMode, sizeof(poolMode), "%s", meta.poolMode.c_str());

    uint64_t wsSize = 0;
    aclOpExecutor *executor = nullptr;
    auto ret = aclnnRoiExtractorGetWorkspaceSize(featsList, roisT, nullptr, meta.finestScale, meta.roiScaleFactor,
                                                 scaleArr, meta.pooledH, meta.pooledW, meta.sampleNum, poolMode,
                                                 meta.aligned, yT, &wsSize, &executor);
    if (ret != ACLNN_SUCCESS) {
        printf("case=%s GetWorkspaceSize failed ret=%d\n", meta.name.c_str(), (int)ret);
        pass = false;
    } else {
        void *ws = nullptr;
        if (wsSize > 0) {
            aclrtMalloc(&ws, wsSize, ACL_MEM_MALLOC_HUGE_FIRST);
        }
        ret = aclnnRoiExtractor(ws, wsSize, executor, stream);
        if (ret != ACLNN_SUCCESS) {
            printf("case=%s aclnnRoiExtractor failed ret=%d\n", meta.name.c_str(), (int)ret);
            pass = false;
        } else {
            aclrtSynchronizeStream(stream);
            std::vector<char> host(yBytes);
            aclrtMemcpy(host.data(), yBytes, yDev, yBytes, ACL_MEMCPY_DEVICE_TO_HOST);
            // compare
            const double rtol = (meta.dtype == ACL_FLOAT16) ? 1.0e-3 : 1.0e-5;
            const double atol = rtol;
            int64_t bad = 0;
            double maxDiff = 0.0;
            const size_t elems = golden.size();
            auto readElem = [&](size_t i) -> double {
                if (meta.dtype == ACL_FLOAT16) {
                    uint16_t h;
                    memcpy(&h, host.data() + i * 2, 2);
                    // fp16 -> fp32 bit-exact conversion
                    uint32_t sign = (h >> 15) & 0x1;
                    uint32_t exp = (h >> 10) & 0x1f;
                    uint32_t frac = h & 0x3ff;
                    uint32_t bits;
                    if (exp == 0) {
                        bits = (sign << 31) | (frac << 13); // subnormal -> fp32 subnormal-ish
                    } else {
                        bits = (sign << 31) | ((exp - 15 + 127) << 23) | (frac << 13);
                    }
                    float f;
                    memcpy(&f, &bits, 4);
                    return static_cast<double>(f);
                }
                float f;
                memcpy(&f, host.data() + i * 4, 4);
                return static_cast<double>(f);
            };
            for (size_t i = 0; i < elems; i++) {
                const double got = readElem(i);
                const double ref = static_cast<double>(golden[i]);
                const double diff = std::fabs(got - ref);
                if (diff > maxDiff) {
                    maxDiff = diff;
                }
                if (diff > atol + rtol * std::fabs(ref)) {
                    bad++;
                }
            }
            pass = (bad == 0);
            printf("case=%-28s dtype=%-8s shape=[%lld,%lld,%lld,%lld] bad=%lld/%zu max_diff=%.3e -> %s\n",
                   meta.name.c_str(), (meta.dtype == ACL_FLOAT16) ? "fp16" : "fp32", (long long)meta.roisNum,
                   (long long)meta.channels, (long long)meta.pooledH, (long long)meta.pooledW, (long long)bad, elems,
                   maxDiff, pass ? "PASS" : "FAIL");
        }
        if (ws != nullptr) {
            aclrtFree(ws);
        }
    }

    for (auto t : featsT) {
        aclDestroyTensor(t);
    }
    aclDestroyTensor(roisT);
    aclDestroyTensor(yT);
    aclDestroyTensorList(featsList);
    aclDestroyFloatArray(scaleArr);
    for (auto p : featsDev) {
        if (p != nullptr) {
            aclrtFree(p);
        }
    }
    aclrtFree(roisDev);
    aclrtFree(yDev);
    aclrtDestroyStream(stream);
    aclrtResetDevice(deviceId);
    return true;
}

} // namespace

int main(int argc, char **argv)
{
    if (argc < 2) {
        printf("usage: %s <case_dir> [device_id]\n", argv[0]);
        return -1;
    }
    const std::string caseDir = argv[1];
    const int32_t deviceId = (argc > 2) ? atoi(argv[2]) : 0;

    std::ifstream idx(caseDir + "/index.txt");
    if (!idx.is_open()) {
        printf("open index.txt failed: %s\n", caseDir.c_str());
        return -1;
    }
    std::vector<std::string> names;
    std::string line;
    while (std::getline(idx, line)) {
        line = Trim(line);
        if (!line.empty()) {
            names.push_back(line);
        }
    }
    int passCnt = 0;
    int failCnt = 0;
    for (const auto &n : names) {
        std::string cn;
        bool pass = false;
        if (!RunOneCase(deviceId, caseDir + "/" + n, cn, pass)) {
            printf("case=%s run error\n", n.c_str());
            failCnt++;
            continue;
        }
        if (pass) {
            passCnt++;
        } else {
            failCnt++;
        }
    }
    printf("===== ST summary: %d passed, %d failed, total %zu =====\n", passCnt, failCnt, names.size());
    return failCnt == 0 ? 0 : 1;
}
