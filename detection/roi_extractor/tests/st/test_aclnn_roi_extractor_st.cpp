/*!
 * \file test_aclnn_roi_extractor_st.cpp
 * \brief On-board ST runner: loads cases generated by golden.py, runs
 * aclnnRoiExtractor on the NPU, downloads results and compares against the
 * golden binaries (rtol/atol: fp32 1e-5, fp16 1e-3).
 *
 * Build & run (custom op package installed under a local opp root):
 *   g++ test_aclnn_roi_extractor_st.cpp \
 *       -I <vendor>/op_api/include/aclnnop -I $ASCEND_HOME_PATH/include \
 *       -I $ASCEND_HOME_PATH/include/aclnn \
 *       -L <vendor>/op_api/lib -L $ASCEND_HOME_PATH/lib64 \
 *       -lcust_opapi -lascendcl -lnnopbase -lc_sec \
 *       -Wl,-rpath=<vendor>/op_api/lib -o test_roi_extractor_st
 *   ASCEND_CUSTOM_OPP_PATH=<vendor> ./test_roi_extractor_st <case_dir> [device_id]
 */

