/*!
 * \file nlast_transpose_nddma_bench_def.cpp
 * \brief NlastTransposeNddmaBench ascendc op def（仅 ascend950 / arch35）
 */

#include "register/op_def_registry.h"

namespace ops {
class NlastTransposeNddmaBench : public OpDef {
public:
    explicit NlastTransposeNddmaBench(const char *name) : OpDef(name)
    {
        this->Input("x")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_FLOAT, ge::DT_INT8})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND, ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND, ge::FORMAT_ND, ge::FORMAT_ND});
        this->Output("y")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_FLOAT, ge::DT_INT8})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND, ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND, ge::FORMAT_ND, ge::FORMAT_ND});

        this->Attr("is_mte3").AttrType(OPTIONAL).Int(1);

        OpAICoreConfig config_95;
        config_95.DynamicCompileStaticFlag(true)
            .DynamicFormatFlag(true)
            .DynamicRankSupportFlag(true)
            .DynamicShapeSupportFlag(true)
            .NeedCheckSupportFlag(false)
            .PrecisionReduceFlag(true)
            .ExtendCfgInfo("opFile.value", "nlast_transpose_nddma_bench_apt");

        this->AICore().AddConfig("ascend950", config_95);
    }
};

OP_ADD(NlastTransposeNddmaBench);
}  // namespace ops
