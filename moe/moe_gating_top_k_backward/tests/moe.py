def moe_finalize_routing_np(
    expanded_permuted_rows,
    skip1,
    skip2_optional,
    bias,
    scales,
    expanded_src_to_dst_row,
    expert_for_source_row,
):
    out = skip1
    if skip2_optional is not None:
        out = skip1 + skip2_optional
    num_rows = skip1.shape[0]
    K = expanded_src_to_dst_row.shape[0] // num_rows

    for i in range(num_rows):
        for k in range(K):
            dst_row = expanded_permuted_rows[
                expanded_src_to_dst_row[k * num_rows + i], :
            ]
            expert_id = expert_for_source_row[i, k]
            out[i, :] += scales[i, k] * (dst_row + bias[expert_id, :])

    return out


def moe_finalize_routing_v2_np(
    expanded_x,
    expanded_row_idx,
    x1,
    x2,
    bias,
    scales,
    expert_idx,
    x,
    a1,
    a2,
    v,
    drop_pad_mode,
    zero_expert_range: List,
    copy_expert_range: List,
    constant_expert_range: List,
):
    from en_dtypes import float4_e1m2 as hifloat4

    def _e6m2_reciprocal_to_bf16(a: numpy.uint8):
        # 处理特殊值
        if a == 0xFF:
            return bfloat16(numpy.nan)
        if a == 0x00:
            return bfloat16(numpy.inf)  # 2^-48 的倒数极大，直接给 inf
        # 1. 位运算提取指数和尾数
        E6 = a >> 2
        M2 = a & 0x03
        # 2. 计算 1/a 的实际大小
        # 原值 a = 2^(E6 - 48) * (1 + M2 / 4)
        # 倒数 1/a = 2^(48 - E6) / (1 + M2 / 4)
        inv_val = (2.0 ** (48 - E6)) / (1.0 + M2 * 0.25)
        # 3. 转为 bfloat16
        return bfloat16(inv_val)

    def _e6m2_to_bf16(x_uint8):
        # 确保输入是 uint8 类型的 ndarray
        x_uint8 = numpy.asarray(x_uint8, dtype=numpy.uint8)
        # 提取 6位指数 (右移2位) 和 2位尾数 (取低2位)
        E6 = (x_uint8 >> 2).astype(numpy.float32)
        M2 = (x_uint8 & 0x03).astype(numpy.float32)
        # 还原公式: x = 2^(E6 - 48) * (1 + M2 / 4)
        x_f32 = (2.0 ** (E6 - 48.0)) * (1.0 + M2 * 0.25)
        # 处理 NaN (根据你的代码，0xFF 对应 NaN)
        x_f32 = numpy.where(x_uint8 == 0xFF, numpy.nan, x_f32)
        # 转换为 bfloat16
        return x_f32.astype(bfloat16)

    def _e1m2_to_bf16(in_tensor):
        def _cvt_fp4_e1m2_to_bfloat16(x):
            Fp4e1m2ToBf16 = {
                "0": 0.0,
                "1": 0.25,
                "2": 0.5,
                "3": 0.75,
                "4": 1.0,
                "5": 1.25,
                "6": 1.5,
                "7": 1.75,
                "8": -0.0,
                "9": -0.25,
                "10": -0.5,
                "11": -0.75,
                "12": -1.0,
                "13": -1.25,
                "14": -1.5,
                "15": -1.75,
            }
            return Fp4e1m2ToBf16[str(x)]

        shape_tensor = in_tensor.shape
        multi_shape = numpy.prod(shape_tensor)
        in_tensor = in_tensor.reshape(multi_shape).view(numpy.uint8)
        bfloat16_tensor = numpy.zeros(multi_shape).astype(bfloat16)
        for i in range(multi_shape):
            bfloat16_tensor[i] = _cvt_fp4_e1m2_to_bfloat16(in_tensor[i])
        return bfloat16_tensor.reshape(shape_tensor)

    # 适配hif4
    is_hif4_dequant = False
    out_type = numpy.float32
    if expanded_x.dtype == numpy.float32:
        out_type = numpy.float64
    elif expanded_x.dtype == hifloat4:
        is_hif4_dequant = True
        out_type = bfloat16

    bsk = expanded_row_idx.shape[0]
    h = expanded_x.shape[-1]
    if h == 0:
        return numpy.array([], dtype=out_type)
    expanded_x = expanded_x.reshape(-1, h)
    K = 1
    if scales is not None:
        K = scales.shape[1]
    num_rows = bsk // K

    out = numpy.zeros((num_rows, h), dtype=out_type)
    if x1 is not None:
        out = out + x1
    if x2 is not None:
        out = out + x2

    for i in range(num_rows):
        for k in range(K):
            if drop_pad_mode == 0 or drop_pad_mode == 1:
                expanded_row_idx_idx = k * num_rows + i
            else:
                expanded_row_idx_idx = i * K + k
            # drop_pad
            expanded_row_idx_value = expanded_row_idx[expanded_row_idx_idx]
            if expanded_row_idx_value == -1:
                continue
            if drop_pad_mode != 1 and drop_pad_mode != 3:
                expanded_row_idx_value = expanded_row_idx[expanded_row_idx_idx]
                if expanded_row_idx_value >= expanded_x.shape[0]:
                    continue
            # 适配hif4
            if is_hif4_dequant:
                dst_row = numpy.zeros(h, dtype=out_type)
                src_row = expanded_x[expanded_row_idx[expanded_row_idx_idx], :].copy()
                src_row = _e1m2_to_bf16(src_row)
                blk_size = 64
                num_blk = scales.shape[2]
                for scale_idx in range(num_blk):
                    # 每64个元素一个scale_value，需要从提取Ea、每8个元素一个Eb、每4个元素一个Ec
                    scale_value = scales[i, k, scale_idx].view(numpy.uint32)
                    a = numpy.uint8(scale_value & 0xFF)  # 低8位
                    b = numpy.uint8((scale_value >> 8) & 0xFF)  # 中8位
                    c = numpy.uint16((scale_value >> 16) & 0xFFFF)  # 高16位
                    Ea = _e6m2_to_bf16(a)  # bf16标量
                    j = numpy.arange(blk_size)  # 0,1,...,63
                    # uint8 64元素ndarray，每8个元素一个Ebi值
                    Eb = ((b >> (j // 8)) & 1).astype(numpy.uint8)
                    # uint8 64元素ndarray，每4个元素一个Eci值
                    Ec = ((c >> (j // 4)) & 1).astype(numpy.uint8)

                    # TODO: Ea_bf16等价于1/Ea_rec_bf16
                    scale_factor = 2 ** (Eb + Ec) * Ea
                    # Ea_rec_bf16 = _e6m2_reciprocal_to_bf16(a)
                    # scale_factor = 2**(Eb+Ec)/Ea_rec_bf16
                    scale_factor = scale_factor.astype(out_type)

                    # 用scale_factor去反量化64个片段
                    start_idx = scale_idx * blk_size
                    end_idx = start_idx + blk_size
                    dst_row[start_idx:end_idx] = (
                        src_row[start_idx:end_idx] * scale_factor
                    )
                if bias is not None and expert_idx is not None:
                    expert_id = expert_idx[i, k]
                    dst_row = dst_row + bias[expert_id, :].astype(out_type)
            else:
                # 先获取 expert_id
                if x is not None and expert_idx is not None:
                    zero_expert_start, zero_expert_end = zero_expert_range
                    copy_expert_start, copy_expert_end = copy_expert_range
                    constant_expert_start, constant_expert_end = constant_expert_range
                    expert_id = expert_idx[i, k]
                    # --- 1. zero expert: 直接 skip ---
                    if zero_expert_start <= expert_id < zero_expert_end:
                        continue  # 跳过当前k的所有计算，不贡献到out
                    elif copy_expert_start <= expert_id < copy_expert_end:
                        # copy expert: 用x[i]替换expanded_x
                        dst_row = x[i, :].astype(out_type)
                    elif (
                        x is not None
                        and v is not None
                        and a1 is not None
                        and a2 is not None
                        and constant_expert_start <= expert_id < constant_expert_end
                    ):
                        # constant expert: 用a1[num]*x[i] + a2[num]*v[num]替换expanded_x
                        row_idx = expert_id - constant_expert_start
                        print("row_idx=", row_idx)
                        dst_row = (
                            a1[row_idx, :] * x[i, :] + a2[row_idx, :] * v[row_idx, :]
                        ).astype(out_type)
                    else:
                        dst_row = expanded_x[
                            expanded_row_idx[expanded_row_idx_idx], :
                        ].astype(out_type)
                else:
                    dst_row = expanded_x[
                        expanded_row_idx[expanded_row_idx_idx], :
                    ].astype(out_type)
                if bias is not None and expert_idx is not None:
                    expert_id = expert_idx[i, k]
                    dst_row = dst_row + bias[expert_id, :].astype(out_type)
                if scales is not None:
                    dst_row = dst_row * scales[i, k].astype(out_type)
            out[i, :] = out[i, :] + dst_row
    return out


