@register_golden(["moe_finalize_routing_v2"])
def _moe_finalize_routing(context: "tbetoolkits.UniversalTestcaseStructure"):
    expanded_x = context.input_arrays[0]
    expanded_row_idx = context.input_arrays[1]
    x1 = context.input_arrays[2]
