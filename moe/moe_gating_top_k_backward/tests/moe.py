def moe_gating_top_k_numpy(
    x: numpy.ndarray,
    bias: numpy.ndarray,
    k: int,
    k_group: int = 1,
    group_count: int = 1,
    group_select_mode: int = 0,
    renorm: int = 0,
    norm_type: int = 0,
    y2_flag: bool = False,
    routed_scaling_factor: float = 1.0,
    eps: float = 1e-20,
) -> tuple:
    ori_dtype = x.dtype
    x = x.astype("float32")
    if bias is not None:
        bias = bias.astype("float32")
    if norm_type == 0:  # softmax
        x, _, _ = softmax_func(x, -1)
    elif norm_type == 1:
        x = 1 / (1 + numpy.exp(-x))  # sigmoid
    elif norm_type == 2:
        x = numpy.sqrt(numpy.log1p(numpy.exp(x)))  # softplus
    original_x = x
    if bias is not None:
        x = x + bias
    if group_count > 1:
        x = x.reshape(x.shape[0], group_count, -1)
        if group_select_mode == 0:
            group_x = numpy.amax(x, axis=-1)
        else:
            group_x = numpy.partition(x, -2, axis=-1)[..., -2:].sum(axis=-1)
        indices = numpy.argsort(-group_x, axis=-1, kind="stable")[
            :, :k_group
        ]  # Indices of top-k_group

        # mask = numpy.zeros_like(x[..., 0], dtype=bool)
        # numpy.put_along_axis(mask, indices, True, axis=-1)
        # x = (x * mask[..., numpy.newaxis]).reshape(x.shape[0], -1)

        mask = numpy.ones((x.shape[0], group_count), dtype=bool)  # 创建全 1 的掩码
        mask[numpy.arange(x.shape[0])[:, None], indices] = (
            False  # 在指定索引处设置为 False
        )
        x = numpy.where(
            mask[..., None], float("-inf"), x
        )  # 用 -inf 填充掩码为 True 的位置
        x = x.reshape(x.shape[0], -1)

    import torch

    _, indices = torch.sort(torch.from_numpy(x), dim=-1, stable=True, descending=True)
    indices = numpy.asarray(indices[:, :k])
    # indices = numpy.argsort(-x, axis=-1, kind='stable')  # Sorting in descending order and getting top-k indices
    # indices = indices[:, :k]
    y = numpy.take_along_axis(original_x, indices, axis=1)

    if norm_type != 0 or renorm != 0:
        y /= numpy.sum(y, axis=-1, keepdims=True) + eps
    y *= routed_scaling_factor
    if y2_flag:
        y2 = original_x
    else:
        y2 = None
    return y.astype(ori_dtype), indices.astype(numpy.int32), y2


