def moe_re_routing_torch(
    tokens, expert_token_num_per_rank, idx_type, per_token_scales=None
):
    """
    A torch implementation of MoeReRouting
    """
    import torch

    token_num, token_length = tokens.shape
    rank_num, expert_num = expert_token_num_per_rank.shape
    permute_tokens = torch.zeros((token_num, token_length), dtype=tokens.dtype)
    permute_token_idx = torch.zeros(token_num, dtype=torch.int32)
    if per_token_scales is not None:
        if per_token_scales.dim() == 1:
            scalar_length = 1
            permute_per_token_scales = torch.zeros(token_num, dtype=torch.float32)
        else:
            scalar_length = per_token_scales.shape[1]
            permute_per_token_scales = torch.zeros(
                (token_num, scalar_length), dtype=torch.float32
            )
    else:
        permute_per_token_scales = None

    expert_token_num = expert_token_num_per_rank.sum(dim=0)
    per_expert_offset = torch.zeros(expert_num, dtype=expert_token_num_per_rank.dtype)
    # cumsum计算累计和，得到每个专家的起始偏移量
    per_expert_offset[1:] = expert_token_num.cumsum(dim=0)[:-1]
    src_offset = 0
    for cur_rank in range(rank_num):  # 遍历每个rank
        for expert in range(expert_num):  # 遍历每个专家
            # 当前rank当前专家分配的令牌数
            num_tokens = expert_token_num_per_rank[cur_rank, expert]
            if num_tokens == 0:
                continue
            dst_start = per_expert_offset[expert]
            dst_end = dst_start + num_tokens
            src_end = src_offset + num_tokens
            permute_tokens[dst_start:dst_end] = tokens[src_offset:src_end]
            if idx_type == 0:
                permute_token_idx[dst_start:dst_end] = torch.arange(
                    src_offset, src_end, dtype=torch.int32
                )
            else:
                permute_token_idx[src_offset:src_end] = torch.arange(
                    dst_start, dst_end, dtype=torch.int32
                )

            if per_token_scales is not None:
                permute_per_token_scales[dst_start:dst_end] = per_token_scales[
                    src_offset:src_end
                ]

            src_offset = src_end
            per_expert_offset[expert] = dst_end

    return permute_tokens, permute_per_token_scales, permute_token_idx, expert_token_num


def moe_re_routing_numpy(
    tokens, expert_token_num_per_rank, idx_type, per_token_scales=None
):
    """
    A NumPy implementation of MoeReRouting
    """
    token_num, token_length = tokens.shape
    rank_num, expert_num = expert_token_num_per_rank.shape

    permute_tokens = numpy.zeros((token_num, token_length), dtype=tokens.dtype)
    permute_token_idx = numpy.zeros(token_num, dtype=numpy.int32)

    if per_token_scales is not None:
        if per_token_scales.ndim == 1:
            scalar_length = 1
            permute_per_token_scales = numpy.zeros(
                token_num, dtype=per_token_scales.dtype
            )
        else:
            scalar_length = per_token_scales.shape[1]
            permute_per_token_scales = numpy.zeros(
                (token_num, scalar_length), dtype=per_token_scales.dtype
            )
    else:
        permute_per_token_scales = None

    expert_token_num = numpy.sum(expert_token_num_per_rank, axis=0)
    per_expert_offset = numpy.zeros(expert_num, dtype=expert_token_num_per_rank.dtype)
    per_expert_offset[1:] = numpy.cumsum(expert_token_num)[:-1]

    src_offset = 0
    for cur_rank in range(rank_num):
        for expert in range(expert_num):
            num_tokens = expert_token_num_per_rank[cur_rank, expert]
            if num_tokens == 0:
                continue
            dst_start = per_expert_offset[expert]
            dst_end = dst_start + num_tokens
            src_end = src_offset + num_tokens

            permute_tokens[dst_start:dst_end] = tokens[src_offset:src_end]
            if idx_type == 0:
                permute_token_idx[dst_start:dst_end] = numpy.arange(
                    src_offset, src_end, dtype=numpy.int32
                )
            else:
                permute_token_idx[src_offset:src_end] = numpy.arange(
                    dst_start, dst_end, dtype=numpy.int32
                )

            if per_token_scales is not None:
                permute_per_token_scales[dst_start:dst_end] = per_token_scales[
                    src_offset:src_end
                ]

            src_offset = src_end
            per_expert_offset[expert] = dst_end

    return permute_tokens, permute_per_token_scales, permute_token_idx, expert_token_num


