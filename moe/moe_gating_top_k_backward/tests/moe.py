def softmax_func(x, axis=None):
    if "float16" in x.dtype.name:
        x = x.astype(numpy.float32)
    x_max = x.max(axis=axis, keepdims=True)
    x_sub = x - x_max
    y = numpy.exp(x_sub)
    x_sum = y.sum(axis=axis, keepdims=True)
    ans = y / x_sum
    return ans, x_max, x_sum


@register_golden(["moe_gating_top_k_softmax"])
def _moe_gating_topk_softmax(context: "tbetoolkits.UniversalTestcaseStructure"):
    gating = context.input_arrays[0]
    finished_optional = context.input_arrays[1]
    k = context.other_compilation_params["k"]  # required attribute

    num_expert = gating.shape[-1]
    softmax, _, _ = softmax_func(gating, -1)

    indices = numpy.argsort(-softmax, axis=-1, kind="stable")
    indices = indices[:, :k]
    out = numpy.take_along_axis(softmax, indices, axis=-1)
    if finished_optional is not None:
        finished_optional = finished_optional.reshape(finished_optional.shape[0], 1)
        finished_optional = numpy.tile(finished_optional, (1, k))
        indices = numpy.where(finished_optional, num_expert, indices)
    source_row_out = (
        numpy.arange(out.shape[0] * out.shape[1], dtype=numpy.int32)
        .reshape([out.shape[1], out.shape[0]])
        .transpose(1, 0)
    )
    if "float16" in gating.dtype.name:
        out = out.astype(gating.dtype)
    return out, indices, source_row_out


