def moe_gating_top_k_backward_numpy(
    x_norm: numpy.ndarray,
    grad_y: numpy.ndarray,
    expert_idx: numpy.ndarray,
    renorm: int = 0,
    norm_type: int = 1,
    routed_scaling_factor: float = 1.0,
    eps: float = 1e-20,
) -> numpy.ndarray:
    """
    A numpy implementation of MoeGatingTopKBackward.
    """
    if norm_type != 1:
        raise ValueError("MoeGatingTopKBackward only supports norm_type=1 currently.")
    if x_norm.ndim != 2 or grad_y.ndim != 2 or expert_idx.ndim != 2:
        raise ValueError("x_norm, grad_y and expert_idx must be 2D arrays.")
    if grad_y.shape != expert_idx.shape:
        raise ValueError("grad_y and expert_idx must have the same shape.")
    if x_norm.shape[0] != grad_y.shape[0]:
        raise ValueError("x_norm and grad_y must have the same first dimension.")

    _ = renorm
    out_dtype = grad_y.dtype
    x_norm_fp32 = x_norm.astype("float32")
    grad_y_scaled = grad_y.astype("float32") * numpy.float32(routed_scaling_factor)
    expert_idx_int64 = expert_idx.astype(numpy.int64)

    if numpy.any(expert_idx_int64 < 0) or numpy.any(
        expert_idx_int64 >= x_norm_fp32.shape[1]
    ):
        raise ValueError(
            "expert_idx contains an index outside x_norm's last dimension."
        )

    w_prime = numpy.take_along_axis(x_norm_fp32, expert_idx_int64, axis=1)
    denominator = numpy.sum(w_prime, axis=-1, keepdims=True) + numpy.float32(eps)
    topk_prob = w_prime / denominator
    beta = numpy.sum(topk_prob * grad_y_scaled, axis=-1, keepdims=True)
    grad_w_prime = (grad_y_scaled - beta) / denominator

    grad_norm_x = numpy.zeros_like(x_norm_fp32)
    row_idx = numpy.repeat(
        numpy.arange(x_norm_fp32.shape[0])[:, numpy.newaxis],
        expert_idx_int64.shape[1],
        axis=1,
    )
    numpy.add.at(grad_norm_x, (row_idx, expert_idx_int64), grad_w_prime)

    grad_x = x_norm_fp32 * (1.0 - x_norm_fp32) * grad_norm_x
    return grad_x.astype(out_dtype)


