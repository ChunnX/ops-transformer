def expert_dispatch_numpy(
    x: numpy.ndarray, expert_id: numpy.ndarray, scale: numpy.ndarray, expert_range: List
):
    expert_start = expert_range[0]
    expert_end = expert_range[1]
    k = expert_id.shape[-1]
    expert_id_in = expert_id.copy().reshape(-1)
    actual_expert_total_num = numpy.sum(
        (expert_id_in >= expert_start) & (expert_id_in < expert_end)
    )

    # 排序
    expert_id_in[(expert_id_in < expert_start)] = numpy.int32(
        numpy.iinfo(numpy.int32).max
    )
    sorted_expert_indices = numpy.argsort(expert_id_in, axis=-1, kind="stable")
    sorted_expert_idx = expert_id_in[sorted_expert_indices]
    dispatched_row_idx = sorted_expert_indices

    # gather
    dispatched_x = x[sorted_expert_indices[:actual_expert_total_num] // k, :]
    dispatched_scale = scale[sorted_expert_indices[:actual_expert_total_num] // k]

    # 计算直方图
    expert_tokens_count = numpy.bincount(
        sorted_expert_idx[:actual_expert_total_num] - expert_start
    )
    expert_tokens_count = numpy.concatenate(
        [
            expert_tokens_count,
            numpy.zeros((expert_end - expert_start) - len(expert_tokens_count)),
        ]
    )
    return (
        dispatched_x,
        dispatched_row_idx,
        expert_tokens_count,
        actual_expert_total_num,
        dispatched_scale,
    )


