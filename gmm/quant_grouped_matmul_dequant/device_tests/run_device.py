"""
Iterate qgmmd configs matching the given filters and run each on device
inside a `msprof op` profiling wrap. Each test gets its own subdirectory
under the output root; the OPPROF_* profile directory produced by msprof
lands there. After all tests finish, STATS.txt + per-tag .log files are
generated by parsing every OPPROF_* visualize_data.bin.

Usage:
    # one test
    python run_device.py --shape decode_like --variant dynamic

    # all variants for one shape
    python run_device.py --shape decode_like

    # multiple shapes
    python run_device.py --shape decode_like --shape k_heavy

    # all LIGHT + HEAVY
    python run_device.py

    # LIGHT only / HEAVY only
    python run_device.py --tier LIGHT
    python run_device.py --tier HEAVY

If --out is not given, results land in
    device_tests/out/<shape_names>_YYYY-MM-DD_HH-MM/
"""
import argparse
import csv
import glob
import json
import os
import re
import subprocess
import sys
import time

THIS_DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, THIS_DIR)
from configs import SHAPES, build_all_configs, config_tag, data_tag  # noqa: E402
from data_stage import generate_one, data_is_present  # noqa: E402


def filter_configs(shapes, variants, tier):
    tiers = ("LIGHT", "HEAVY", "QWEN3") if tier == "ALL" else (tier,)
    configs = build_all_configs(tiers=tiers)
    if shapes:
        configs = [c for c in configs if c["name"] in shapes]
    if variants:
        configs = [c for c in configs if c["variant"] in variants]
    return configs


def _run_leaf_name(shapes):
    if shapes:
        ordered = [n for n, *_ in SHAPES if n in shapes]
        prefix = "-".join(ordered) if ordered else "-".join(sorted(shapes))
    else:
        prefix = "all"
    stamp = time.strftime("%Y-%m-%d_%H-%M")
    return f"{prefix}_{stamp}"


def _shapes_epilog():
    lines = ["available shapes:"]
    for name, E, M, K, N in SHAPES:
        lines.append(f"  {name:15s}  E={E:<3d} M={M:<5d} K={K:<6d} N={N}")
    lines.append("")
    lines.append("variants: dynamic, dynamic_u64, dynamic_smooth")
    return "\n".join(lines)


_OPPROF_DIR_RE = re.compile(r"^OPPROF_\d{14}_[A-Z0-9]+$")


def _find_opprof_dir(test_dir):
    candidates = [
        d for d in glob.glob(os.path.join(test_dir, "OPPROF_*"))
        if os.path.isdir(d) and _OPPROF_DIR_RE.match(os.path.basename(d))
    ]
    if not candidates:
        return None
    candidates.sort(key=os.path.getmtime, reverse=True)
    return candidates[0]


def _read_task_duration_us(opprof_dir):
    path = os.path.join(opprof_dir, "OpBasicInfo.csv")
    if not os.path.exists(path):
        return None
    with open(path) as f:
        rows = list(csv.DictReader(f))
    if not rows:
        return None
    pick = rows[0]
    for r in rows:
        if str(r.get("Op Name", "")).startswith("QuantGroupedMatmulDequant"):
            pick = r
            break
    try:
        return float(str(pick.get("Task Duration(us)", "")).strip())
    except (ValueError, TypeError):
        return None


def run_one_msprof(cfg, datadir, test_dir, engine="torch", iterations=20, warmup=3):
    os.makedirs(test_dir, exist_ok=True)
    result_json = os.path.join(test_dir, "result.json")
    stdout_log = os.path.join(test_dir, "msprof_stdout.log")

    run_one = os.path.join(THIS_DIR, "run_one.py")
    # Source the custom_transformer vendor env so CANN dispatches to our
    # custom tiling library instead of the built-in one. Without this,
    # the kernel binary still loads from the vendor path but TilingData
    # is computed by CANN's built-in tiler, leaving custom fields
    # (e.g. wChunkKPasses) at zero — our picker never runs.
    vendor_env = os.path.expanduser(
        "~/.local/ascend-toolkit/vendors/custom_transformer/bin/set_env.bash")
    # Default to chip 1 (device 0 has transient state/msprof contention
    # issues that produce false cos failures). Override with
    # ASCEND_RT_VISIBLE_DEVICES from caller env if set.
    device_id = os.environ.get("ASCEND_RT_VISIBLE_DEVICES", "1")
    extra_args = ""
    if engine == "aclnn":
        extra_args = (f"--engine aclnn --iterations {iterations} "
                      f"--warmup {warmup}")
    cmd = ["bash", "-c",
           f"source {vendor_env} && "
           f"export ASCEND_RT_VISIBLE_DEVICES={device_id} && "
           f"exec msprof op "
           f"--kernel-name=QuantGroupedMatmulDequant "
           f"python3 {run_one} --datadir {datadir} "
           f"--variant {cfg['variant']} --output-json {result_json} "
           f"{extra_args}"]

    t0 = time.time()
    with open(stdout_log, "w") as stdout_fh:
        proc = subprocess.run(cmd, cwd=test_dir, stdout=stdout_fh,
                              stderr=subprocess.STDOUT)
    wall = time.time() - t0

    result = {"cos": 0.0, "pass": False, "wall_ms": 0.0,
              "msprof_rc": proc.returncode, "total_wall_s": wall}
    if os.path.exists(result_json):
        try:
            with open(result_json) as f:
                result.update(json.load(f))
        except Exception as e:
            result["parse_error"] = str(e)

    opprof = _find_opprof_dir(test_dir)
    result["opprof_dir"] = os.path.basename(opprof) if opprof else None
    if opprof:
        td = _read_task_duration_us(opprof)
        if td is not None:
            result["task_duration_us"] = td
    return result


def main():
    p = argparse.ArgumentParser(
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=_shapes_epilog(),
    )
    p.add_argument("--shape", action="append",
                   help="filter: shape name (repeat for multiple)")
    p.add_argument("--variant", action="append",
                   help="filter: variant name")
    p.add_argument("--tier", choices=("LIGHT", "HEAVY", "QWEN3", "ALL"), default="ALL")
    p.add_argument("--out", default=None,
                   help="parent output dir (default: device_tests/out/)")
    p.add_argument("--dataroot", default=None,
                   help="where to stage generated data (default: reuse "
                        "talk/qgmmd/test/data/<shape>)")
    p.add_argument("--regenerate", action="store_true",
                   help="force regeneration of test data")
    p.add_argument("--no-stats", action="store_true",
                   help="skip STATS.txt generation step")
    p.add_argument("--engine", default="torch", choices=("torch", "aclnn"),
                   help="dispatch engine: torch_npu (default, slow init) or "
                        "aclnn (standalone C++ binary, requires aclnn_bench/build/run_aclnn)")
    p.add_argument("--iterations", type=int, default=20,
                   help="aclnn-only: timed iterations per call")
    p.add_argument("--warmup", type=int, default=3,
                   help="aclnn-only: warmup iterations")
    args = p.parse_args()

    configs = filter_configs(args.shape, args.variant, args.tier)
    if not configs:
        print("No matching configs.")
        sys.exit(1)

    parent = os.path.abspath(args.out) if args.out else os.path.join(THIS_DIR, "out")
    outdir = os.path.join(parent, _run_leaf_name(args.shape))
    os.makedirs(outdir, exist_ok=True)
    print(f"Output dir: {outdir}")

    # Reuse the simulator's data/ directory by default so we don't
    # double-generate the same inputs for simulator + device.
    _REPO = os.path.abspath(os.path.join(THIS_DIR, "..", "..", ".."))
    default_data = os.path.join(_REPO, "talk", "qgmmd", "test", "data")
    dataroot = args.dataroot or default_data
    os.makedirs(dataroot, exist_ok=True)
    summary_path = os.path.join(outdir, "SUMMARY.txt")

    with open(summary_path, "w") as summary:
        print(f"Device test run  {time.strftime('%Y-%m-%d %H:%M:%S')}",
              file=summary, flush=True)
        print(f"Out dir: {outdir}", file=summary, flush=True)
        print(f"Configs: {len(configs)}", file=summary, flush=True)
        print("", file=summary, flush=True)
        print(f"Running {len(configs)} configs → {outdir}")

        passes = fails = 0
        for i, cfg in enumerate(configs, 1):
            tag = config_tag(cfg)
            dtag = data_tag(cfg)
            test_dir = os.path.join(outdir, tag)
            os.makedirs(test_dir, exist_ok=True)
            datadir = os.path.join(dataroot, dtag)

            # 1. Generate test data — skip if already cached.
            need_gen = args.regenerate or not data_is_present(datadir, cfg)
            if need_gen:
                try:
                    generate_one(cfg, datadir)
                except Exception as e:
                    with open(os.path.join(test_dir, "generate.log"), "w") as f:
                        f.write(f"generate_one failed: {e}\n")
                    line = (f"  {tag} ... wall=   0s  cos=  0.0000  "
                            f"PASS=False  (generate failed: {e})")
                    print(f"  [{i:3d}/{len(configs)}] {line.lstrip()}")
                    print(line, file=summary, flush=True)
                    fails += 1
                    continue

            # 2. Run the test inside msprof op.
            result = run_one_msprof(cfg, datadir, test_dir,
                                    engine=args.engine,
                                    iterations=args.iterations,
                                    warmup=args.warmup)
            total = result.get("total_wall_s", 0.0)
            kernel_ms = result.get("wall_ms", 0.0)
            cos = result.get("cos", 0.0)
            ok = bool(result.get("pass", False))

            task_us = result.get("task_duration_us")
            opprof_base = result.get("opprof_dir") or "-"
            if task_us is not None:
                kernel_field = f"task_dur={task_us:.3f}µs"
            else:
                kernel_field = f"pyTime={kernel_ms:.2f}ms"
            line = (f"  {tag} ... wall={total:5.1f}s  "
                    f"cos={cos*100:.4f}  PASS={'True' if ok else 'False'}  "
                    f"{kernel_field}  opprof={opprof_base}")
            print(f"  [{i:3d}/{len(configs)}] {line.lstrip()}")
            print(line, file=summary, flush=True)

            if ok:
                passes += 1
            else:
                fails += 1

        print("", file=summary, flush=True)
        print(f"PASS={passes}  FAIL={fails}  TOTAL={len(configs)}",
              file=summary, flush=True)
        print(f"Done at {time.strftime('%Y-%m-%d %H:%M:%S')}",
              file=summary, flush=True)
        print(f"\nPASS={passes}  FAIL={fails}  TOTAL={len(configs)}")

    # 3. Extract STATS.txt from all OPPROF_* dirs.
    if not args.no_stats:
        extract = os.path.join(THIS_DIR, "extract_msprof_stats.py")
        stats_out = os.path.join(outdir, "STATS.txt")
        print(f"Extracting stats → {stats_out}")
        rc = subprocess.call([
            sys.executable, extract,
            "--root", outdir,
            "--out", stats_out,
            "--summary", summary_path,
        ])
        if rc != 0:
            print(f"  (extract_msprof_stats.py exited {rc})")

    sys.exit(0 if fails == 0 else 1)


if __name__ == "__main__":
    main()
