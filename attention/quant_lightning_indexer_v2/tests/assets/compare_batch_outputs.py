"""Use the LI_V2/QLI_V2 shared raw-output batch comparator."""

import importlib.util
import sys
from pathlib import Path


def load_shared_comparator():
    name = "indexer_ttk_batch_output_compare"
    path = (
        Path(__file__).resolve().parents[3]
        / "lightning_indexer_v2/tests/assets/compare_batch_outputs.py"
    )
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot create import spec for {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


if __name__ == "__main__":
    raise SystemExit(load_shared_comparator().main())
