import pytest


def pytest_addoption(parser):
    group = parser.getgroup("batch consistency")
    group.addoption(
        "--consistency-mode",
        choices=("1", "2", "all"),
        default="all",
        help="batch consistency mode: 1=reorder, 2=split, all=both",
    )
    group.addoption(
        "--consistency-seed",
        type=int,
        default=20260806,
        help="seed used for deterministic batch reorder/split",
    )
    group.addoption(
        "--split-count",
        type=int,
        default=2,
        help="number of non-empty groups generated by split mode",
    )
    group.addoption(
        "--batch-groups",
        default=None,
        help="explicit split groups as JSON, for example [[2,0],[3],[1]]",
    )
    group.addoption(
        "--single-batch-consistency",
        action="store_true",
        help="generate inputs from paramset and run batch consistency",
    )
