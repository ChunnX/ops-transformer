#ifndef __CAUSAL_CONV1D_TILING_KEY_H__
#define __CAUSAL_CONV1D_TILING_KEY_H__

#include "causal_conv1d_tiling_data.h"
#include "ascendc/host_api/tiling/template_argument.h"

#define CAUSAL_CONV1D_TPL_INPUT_MODE_FN_VARLEN 0
#define CAUSAL_CONV1D_TPL_INPUT_MODE_FN_BATCH 1
#define CAUSAL_CONV1D_TPL_INPUT_MODE_UPDATE_VARLEN 2
#define CAUSAL_CONV1D_TPL_INPUT_MODE_UPDATE_BATCH 3
#define CAUSAL_CONV1D_TPL_WIDTH_RUNTIME 0
#define CAUSAL_CONV1D_TPL_WIDTH_2 2
#define CAUSAL_CONV1D_TPL_WIDTH_3 3
#define CAUSAL_CONV1D_TPL_WIDTH_4 4
ASCENDC_TPL_ARGS_DECL(
    CausalConv1d,
    ASCENDC_TPL_UINT_DECL(inputModeKey, 2, ASCENDC_TPL_UI_LIST, CAUSAL_CONV1D_TPL_INPUT_MODE_FN_VARLEN,
                          CAUSAL_CONV1D_TPL_INPUT_MODE_FN_BATCH, CAUSAL_CONV1D_TPL_INPUT_MODE_UPDATE_VARLEN,
                          CAUSAL_CONV1D_TPL_INPUT_MODE_UPDATE_BATCH),
    ASCENDC_TPL_UINT_DECL(widthKey, 3, ASCENDC_TPL_UI_LIST, CAUSAL_CONV1D_TPL_WIDTH_RUNTIME, CAUSAL_CONV1D_TPL_WIDTH_2,
                          CAUSAL_CONV1D_TPL_WIDTH_3, CAUSAL_CONV1D_TPL_WIDTH_4));

#define CAUSAL_CONV1D_TPL_SEL_ENTRY(INPUT_MODE, WIDTH)                                                                 \
    ASCENDC_TPL_ARGS_SEL(ASCENDC_TPL_UINT_SEL(inputModeKey, ASCENDC_TPL_UI_LIST, INPUT_MODE),                          \
                         ASCENDC_TPL_UINT_SEL(widthKey, ASCENDC_TPL_UI_LIST, WIDTH),                                   \
                         ASCENDC_TPL_TILING_STRUCT_SEL(CausalConv1dTilingData))

ASCENDC_TPL_SEL(CAUSAL_CONV1D_TPL_SEL_ENTRY(CAUSAL_CONV1D_TPL_INPUT_MODE_UPDATE_VARLEN,
                                            CAUSAL_CONV1D_TPL_WIDTH_RUNTIME),
                CAUSAL_CONV1D_TPL_SEL_ENTRY(CAUSAL_CONV1D_TPL_INPUT_MODE_UPDATE_BATCH, CAUSAL_CONV1D_TPL_WIDTH_RUNTIME),
                CAUSAL_CONV1D_TPL_SEL_ENTRY(CAUSAL_CONV1D_TPL_INPUT_MODE_FN_VARLEN, CAUSAL_CONV1D_TPL_WIDTH_2),
                CAUSAL_CONV1D_TPL_SEL_ENTRY(CAUSAL_CONV1D_TPL_INPUT_MODE_FN_VARLEN, CAUSAL_CONV1D_TPL_WIDTH_3),
                CAUSAL_CONV1D_TPL_SEL_ENTRY(CAUSAL_CONV1D_TPL_INPUT_MODE_FN_VARLEN, CAUSAL_CONV1D_TPL_WIDTH_4),
                CAUSAL_CONV1D_TPL_SEL_ENTRY(CAUSAL_CONV1D_TPL_INPUT_MODE_FN_BATCH, CAUSAL_CONV1D_TPL_WIDTH_2),
                CAUSAL_CONV1D_TPL_SEL_ENTRY(CAUSAL_CONV1D_TPL_INPUT_MODE_FN_BATCH, CAUSAL_CONV1D_TPL_WIDTH_3),
                CAUSAL_CONV1D_TPL_SEL_ENTRY(CAUSAL_CONV1D_TPL_INPUT_MODE_FN_BATCH, CAUSAL_CONV1D_TPL_WIDTH_4));

#undef CAUSAL_CONV1D_TPL_SEL_ENTRY

#endif // __CAUSAL_CONV1D_TILING_KEY_H__
