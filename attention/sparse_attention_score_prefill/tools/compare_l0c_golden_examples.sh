#!/bin/bash
# ============================================================
# compare_l0c_golden.py 调用实例
# ============================================================
# 前置条件:
#   1. 远程服务器: 121.37.53.41:10001, conda env: rrh
#   2. 脚本位置: /tmp/compare_l0c_golden.py (已 scp 上传)
#   3. golden dump 已生成 (需 GOLDEN_DUMP=1 运行过测试)
#
# 环境变量:
#   TORCH_DEVICE_BACKEND_AUTOLOAD=0  # 避免 torch_npu 加载失败
# ============================================================

PYBIN=/root/miniconda3/envs/rrh/bin/python
WORKDIR=/opt/rrh/code3/ops-transformer/attention/sparse_attention_score_prefill
SCRIPT=/tmp/compare_l0c_golden.py
export TORCH_DEVICE_BACKEND_AUTOLOAD=0

cd $WORKDIR

# ============================================================
# 实例 1: 基本用法 — 命令行传入 L0C dump 值, 自动检测 layout
# ============================================================
# 适用场景: 从 NPU 日志中复制 DumpTensor 输出值, 直接比对
# 参数:
#   --golden     golden .pt 文件路径
#   --l0c-dump   逗号分隔的 L0C dump 值 (从日志复制)
#   --M          逻辑 M (行数, 如 groupCount * groupSize)
#   --N          逻辑 N (列数, 如 D=128)
#   --layout     auto (自动尝试 ZN 和 NZ, 选匹配率高的)

$PYBIN $SCRIPT \
    --golden golden_dumps/run_1002469_1786367140853575720/pv_Opartial_q0_h0_t0.pt \
    --l0c-dump "4.649417, -0.075913, 1.414795, -0.521435, -1.711680, 1.437604, 1.918134, 1.840935, 0.670967, 1.746472, -0.316954, 3.360804, 5.635571, -7.965329, 1.178799, 2.574928" \
    --M 1 --N 128

# ============================================================
# 实例 2: 显示所有元素的逐值比对
# ============================================================
# 适用场景: 需要查看每个元素的比对细节
# 参数:
#   --show-all   输出所有覆盖元素的逐值比对表

$PYBIN $SCRIPT \
    --golden golden_dumps/run_1002469_1786367140853575720/pv_Opartial_q0_h0_t0.pt \
    --l0c-dump "4.649417, -0.075913, 1.414795, -0.521435, -1.711680, 1.437604, 1.918134, 1.840935, 0.670967, 1.746472, -0.316954, 3.360804, 5.635571, -7.965329, 1.178799, 2.574928" \
    --M 1 --N 128 --show-all

# ============================================================
# 实例 3: 指定 layout (跳过自动检测)
# ============================================================
# 适用场景: 已知 L0C 使用 ZN 布局, 跳过 NZ 尝试
# 参数:
#   --layout zn  只用 ZN 布局解析

$PYBIN $SCRIPT \
    --golden golden_dumps/run_1002469_1786367140853575720/pv_Opartial_q0_h0_t0.pt \
    --l0c-dump "4.649417, -0.075913, 1.414795, -0.521435, -1.711680, 1.437604, 1.918134, 1.840935, 0.670967, 1.746472, -0.316954, 3.360804, 5.635571, -7.965329, 1.178799, 2.574928" \
    --M 1 --N 128 --layout zn

# ============================================================
# 实例 4: 从文件读取 L0C dump 值
# ============================================================
# 适用场景: dump 值较多, 不适合放在命令行参数中
# 文件格式: 每行一个浮点数, 或逗号分隔, 或空格分隔
# 准备文件:
#   echo "4.649417, -0.075913, 1.414795, ..." > /tmp/l0c_dump_q0_h0_t0.txt

$PYBIN $SCRIPT \
    --golden golden_dumps/run_1002469_1786367140853575720/pv_Opartial_q0_h0_t0.pt \
    --l0c-file /tmp/l0c_dump_q0_h0_t0.txt \
    --M 1 --N 128 --show-all

# ============================================================
# 实例 5: 多头场景 (M > 1)
# ============================================================
# 适用场景: test_bf16_minimal_debug_2 (q_heads=2, kv_heads=2, groupSize=1)
# 当 batchGroupCount=2, groupSize=1 时 M=2, N=128
# L0C 物理布局: M_aligned=16, N_aligned=128, 总元素=2048
# dump 需要至少 2048 个元素才能覆盖全部有效数据

$PYBIN $SCRIPT \
    --golden golden_dumps/run_XXX/pv_Opartial_q0_h0_t0.pt \
    --l0c-file /tmp/l0c_dump_multi_head.txt \
    --M 2 --N 128 --show-all

# ============================================================
# 实例 6: 调整容差
# ============================================================
# 适用场景: bf16 精度差异较大时放宽容差
# 参数:
#   --atol 0.05   绝对容差 (默认 0.02)
#   --rtol 0.02   相对容差 (默认 0.01)

$PYBIN $SCRIPT \
    --golden golden_dumps/run_XXX/pv_Opartial_q0_h0_t0.pt \
    --l0c-dump "4.649417, -0.075913, ..." \
    --M 1 --N 128 --atol 0.05 --rtol 0.02

# ============================================================
# 实例 7: 比对 QK 的 S scores (而非 PV 的 O_partial)
# ============================================================
# 适用场景: QK matmul 的 L0C dump (desc=900) 与 golden scores_S 比对
# QK 的 S: M=batchM (如 1), N=validSize (如 128)
# golden 文件: scores_S_q{q}_h{h}_t{t}.pt

$PYBIN $SCRIPT \
    --golden golden_dumps/run_XXX/scores_S_q0_h0_t0.pt \
    --l0c-dump "0.123, 0.456, ..." \
    --M 1 --N 128 --layout zn --show-all
