/*!
 * The public aclnn header (aclnnop/aclnn_allto_all_matmul_v2.h) is not yet
 * generated by the build, so the two-phase API is declared manually here.
 */
extern "C" aclnnStatus AlltoAllMatmulV2GetWorkspaceSize(
    const aclTensor *context, const aclTensor *x1, const aclTensor *x2, const aclTensor *biasOptional,
    const aclTensor *x1ScaleOptional, const aclTensor *x2ScaleOptional, const char *group, int64_t worldSize,
    int64_t hcclBufferSize, int64_t x1QuantMode, int64_t x2QuantMode, int64_t groupSize, const char *commMode,
    int64_t precisionMode, const aclTensor *output, const aclTensor *alltoAllOutOptional, uint64_t *workspaceSize,
    aclOpExecutor **executor);
extern "C" aclnnStatus AlltoAllMatmulV2(void *workspace, uint64_t workspaceSize, aclOpExecutor *executor,
                                        aclrtStream stream);

namespace AlltoAllMatmulV2UT {

class AclnnAlltoAllMatmulV2Test : public testing::TestWithParam<AlltoAllMatmulV2ApiUtParam> {
protected:
    static void SetUpTestCase()
    {
        std::cout << "AlltoAllMatmulV2 AclnnAlltoAllMatmulV2Test SetUp" << std::endl;
    }

    static void TearDownTestCase()
    {
        std::cout << "AlltoAllMatmulV2 AclnnAlltoAllMatmulV2Test TearDown" << std::endl;
    }
};

TEST_P(AclnnAlltoAllMatmulV2Test, param)
{
    auto param = GetParam();
    op::SetPlatformSocVersion(param.soc);
    aclTensor *context = param.context.GetViewDims().empty() ? nullptr : param.context.ToAclTypeRawPtr();
    aclTensor *x1 = param.x1.GetViewDims().empty() ? nullptr : param.x1.ToAclTypeRawPtr();
    aclTensor *x2 = param.x2.GetViewDims().empty() ? nullptr : param.x2.ToAclTypeRawPtr();
    aclTensor *bias = param.bias.GetViewDims().empty() ? nullptr : param.bias.ToAclTypeRawPtr();
    aclTensor *x1Scale = param.x1Scale.GetViewDims().empty() ? nullptr : param.x1Scale.ToAclTypeRawPtr();
    aclTensor *x2Scale = param.x2Scale.GetViewDims().empty() ? nullptr : param.x2Scale.ToAclTypeRawPtr();
    aclTensor *output = param.output.GetViewDims().empty() ? nullptr : param.output.ToAclTypeRawPtr();
    aclTensor *alltoAllOut = param.alltoAllOut.GetViewDims().empty() ? nullptr : param.alltoAllOut.ToAclTypeRawPtr();

    auto ut = OP_API_UT(
        AlltoAllMatmulV2,
        INPUT(context, x1, x2, bias, x1Scale, x2Scale, param.group.c_str(), param.worldSize, param.hcclBufferSize,
              param.x1QuantMode, param.x2QuantMode, param.groupSize, param.commMode.c_str(), param.precisionMode),
        OUTPUT(output, alltoAllOut));
    uint64_t workspace_size = 0;
    aclOpExecutor *executor = nullptr;
    auto aclnnRet = ut.TestGetWorkspaceSizeWithNNopbaseInner(&workspace_size, executor);
    if (param.expectResult == ACLNN_SUCCESS) {
        EXPECT_NE(ACLNN_ERR_PARAM_INVALID, aclnnRet);
    } else {
        EXPECT_EQ(param.expectResult, aclnnRet);
    }
}

INSTANTIATE_TEST_SUITE_P(
    AlltoAllMatmulV2, AclnnAlltoAllMatmulV2Test,
    testing::ValuesIn(GetCasesFromCsv<AlltoAllMatmulV2ApiUtParam>(ReplaceFileExtension2Csv(__FILE__))),
    PrintCaseInfoString<AlltoAllMatmulV2ApiUtParam>);

} // namespace AlltoAllMatmulV2UT
