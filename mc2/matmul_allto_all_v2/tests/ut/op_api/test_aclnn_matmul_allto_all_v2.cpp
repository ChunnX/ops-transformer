// Cover defensive nullptr branches in MatmulAlltoAllV2GetWorkspaceSize that
// the parameterised CSV framework cannot trigger (it always passes non-null
// workspaceSize / executor pointers).
TEST(AclnnMatmulAlltoAllV2NullptrTest, NullWorkspaceSizeAndExecutor)
{
    op::SetPlatformSocVersion(op::SocVersion::ASCEND950);
    TensorDesc context({1, 2052}, ACL_INT32, ACL_FORMAT_ND);
    TensorDesc x1({2048, 1024}, ACL_FLOAT8_E4M3FN, ACL_FORMAT_ND);
    TensorDesc x2({4096, 1024}, ACL_FLOAT8_E4M3FN, ACL_FORMAT_ND);
    TensorDesc x1Scale({2048, 16, 2}, ACL_FLOAT8_E8M0, ACL_FORMAT_ND);
    TensorDesc x2Scale({4096, 16, 2}, ACL_FLOAT8_E8M0, ACL_FORMAT_ND);
    TensorDesc output({4096, 2048}, ACL_BF16, ACL_FORMAT_ND);

    // workspaceSize == nullptr  → covers L95-96
    aclOpExecutor *executor = nullptr;
    auto ret1 =
        MatmulAlltoAllV2GetWorkspaceSize(context.ToAclTypeRawPtr(), x1.ToAclTypeRawPtr(), x2.ToAclTypeRawPtr(), nullptr,
                                         x1Scale.ToAclTypeRawPtr(), x2Scale.ToAclTypeRawPtr(), "group", 2, 1073741824,
                                         6, 6, 4295032864, "urma", output.ToAclTypeRawPtr(), nullptr, &executor);
    EXPECT_EQ(ACLNN_ERR_PARAM_NULLPTR, ret1);

    // executor == nullptr → covers L97-98
    uint64_t workspaceSize = 0;
    auto ret2 =
        MatmulAlltoAllV2GetWorkspaceSize(context.ToAclTypeRawPtr(), x1.ToAclTypeRawPtr(), x2.ToAclTypeRawPtr(), nullptr,
                                         x1Scale.ToAclTypeRawPtr(), x2Scale.ToAclTypeRawPtr(), "group", 2, 1073741824,
                                         6, 6, 4295032864, "urma", output.ToAclTypeRawPtr(), &workspaceSize, nullptr);
    EXPECT_EQ(ACLNN_ERR_PARAM_NULLPTR, ret2);
}

// Cover the MatmulAlltoAllV2 execute function (L158-174) which the CSV-driven
// parameterised tests never call.  The stubbed NnopbaseSetHcclServerType and
// NnopbaseRunWithWorkspace make it safe to call with nullptr executor/workspace.
TEST(AclnnMatmulAlltoAllV2ExecuteTest, ExecuteCoversExecuteFunc)
{
    // MatmulAlltoAllV2 calls NnopbaseSetHcclServerType (stubbed no-op) then
    // aclnnInnerMatmulAlltoAllV2.  With nullptr executor the inner function's
    // NnopbaseGetUnContExecutor returns aclInExecutor=nullptr, inContWsSize=0,
    // the workspaceSize check passes (0 < 0 is false), and the stubbed
    // NnopbaseRunWithWorkspace returns OK → execute returns ACLNN_SUCCESS.
    auto execRet = MatmulAlltoAllV2(nullptr, 0, nullptr, nullptr);
    EXPECT_EQ(ACLNN_SUCCESS, execRet);
}

