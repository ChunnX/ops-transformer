/*!
 * The public aclnn header (aclnnop/aclnn_matmul_allto_all_v2.h) is not yet
 * generated by the build, so the two-phase API is declared manually here.
 */
extern "C" aclnnStatus MatmulAlltoAllV2GetWorkspaceSize(
    const aclTensor *context, const aclTensor *x1, const aclTensor *x2, const aclTensor *biasOptional,
    const aclTensor *x1ScaleOptional, const aclTensor *x2ScaleOptional, const char *group, int64_t worldSize,
    int64_t hcclBufferSize, int64_t x1QuantMode, int64_t x2QuantMode, int64_t groupSize, const char *commMode,
    const aclTensor *output, uint64_t *workspaceSize, aclOpExecutor **executor);
extern "C" aclnnStatus MatmulAlltoAllV2(void *workspace, uint64_t workspaceSize, aclOpExecutor *executor,
                                        aclrtStream stream);

