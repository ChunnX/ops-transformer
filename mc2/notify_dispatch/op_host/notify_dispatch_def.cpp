        this->Attr("local_rank_id").AttrType(REQUIRED).Int();
        this->Attr("ccl_buffer_size").AttrType(REQUIRED).Int();
        this->Attr("round").AttrType(REQUIRED).Int();
        this->Attr("perRoundTokens").AttrType(REQUIRED).Int();

